// Writes evals/RESULTS.md: one line per eval run and per comparison, from the tables in evals/results/*.md.
// The raw results (every reply, grade and interview transcript) live on the `pr-assets/evals` branch, not on main:
//   pnpm evals:fetch                # extracts them into evals/results/ (git-ignored)
//   node evals/summarize.ts         # rewrites evals/RESULTS.md from what is there
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = join(root, 'evals/results');
const files = readdirSync(dir).filter((name) => name.endsWith('.md')).sort();
if (files.length === 0) throw new Error('evals/results is empty. Run pnpm evals:fetch first, or run an eval.');

/** The cells of a Markdown table row, or null for a line that isn't one. */
const cells = (line: string): string[] | null =>
  line.startsWith('|') ? line.slice(1, -1).split('|').map((cell) => cell.trim().replace(/\*\*/g, '')) : null;

const runs: string[] = [];
const comparisons: string[] = [];
for (const file of files) {
  const label = file.slice(0, -3);
  const lines = readFileSync(join(dir, file), 'utf8').split('\n');
  const overall = lines.map(cells).find((row) => row?.[0] === 'overall');
  if (!overall) continue;
  if (label.startsWith('compare')) {
    // | overall | cases | before | after | change | better / worse | at 100 | verdict |
    comparisons.push(`| ${label} | ${overall[2]} | ${overall[3]} | ${overall[4]} | ${overall[7]} |`);
    continue;
  }
  const kind = lines[0]?.startsWith('# Interview') ? 'interview' : 'live';
  const setup = lines[2] ?? '';
  const date = /\d{4}-\d{2}-\d{2}/.exec(setup)?.[0] ?? '';
  const scope = /(\d+) runs of (?:up to )?(\d+) (cases|answers)/.exec(setup);
  const categories = lines.map(cells).filter((row): row is string[] => row !== null && row.length === 2 && /^\d+$/.test(row[1] ?? '') && row[0] !== 'overall');
  runs.push(`| ${label} | ${kind} | ${date} | ${scope ? `${scope[1]} × ${scope[2]} ${scope[3]}` : ''} | ${overall[1]} | ${categories.map(([name, score]) => `${name} ${score}`).join(', ')} |`);
}

writeFileSync(join(root, 'evals/RESULTS.md'), [
  '# Eval results',
  '',
  'Generated by `node evals/summarize.ts`. The raw results behind each line (every reply, grade and interview transcript) are on the',
  '[`pr-assets/evals`](https://github.com/isacssw/serra/tree/pr-assets/evals/evals/results) branch; `pnpm evals:fetch` puts them in',
  '`evals/results/`, which is git-ignored. Live runs are noisy (see README.md › Reading results), so read a change through a comparison.',
  '',
  '## Comparisons',
  '',
  '| Comparison | Before | After | Change ±2 SE | Verdict |',
  '|---|---|---|---|---|',
  ...comparisons,
  '',
  '## Runs',
  '',
  '| Label | Kind | Date | Runs × cases | Overall | Categories |',
  '|---|---|---|---|---|---|',
  ...runs,
  '',
].join('\n'));
console.log(`evals/RESULTS.md: ${runs.length} runs, ${comparisons.length} comparisons`);
